// Writes contract ABIs for the web app. Run after `npx hardhat compile`.
const fs = require("fs");
const path = require("path");

const ART = path.join(__dirname, "..", "artifacts", "contracts");
const OUT = path.join(__dirname, "..", "app", "src", "lib", "abi.ts");

const BYTECODE_OUT = path.join(__dirname, "..", "app", "src", "lib", "bytecode.ts");

const read = (file, name) => JSON.parse(fs.readFileSync(path.join(ART, file, `${name}.json`), "utf8"));
const pick = (file, name) => read(file, name).abi;

const abis = {
  auctionAbi: pick("SilentAuction.sol", "SilentAuction"),
  vaultAbi: pick("SilentVault.sol", "SilentVault"),
  oracleAbi: pick("SilentOracle.sol", "SilentOracle"),
  tokenAbi: pick("test/Mocks.sol", "MockERC20"),
  feedAbi: pick("test/Mocks.sol", "MockAggregator"),
};

// Bytecode for the in-browser deployer (app/src/app/deploy).
const bytecodes = {
  tokenBytecode: read("test/Mocks.sol", "MockERC20").bytecode,
  feedBytecode: read("test/Mocks.sol", "MockAggregator").bytecode,
  oracleBytecode: read("SilentOracle.sol", "SilentOracle").bytecode,
  vaultBytecode: read("SilentVault.sol", "SilentVault").bytecode,
  auctionBytecode: read("SilentAuction.sol", "SilentAuction").bytecode,
};

let src = "// Generated by scripts/export-abi.js. Do not edit.\n";
for (const [name, abi] of Object.entries(abis)) {
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log("Wrote", path.relative(process.cwd(), OUT));

let bsrc = "// Generated by scripts/export-abi.js. Do not edit.\n";
for (const [name, code] of Object.entries(bytecodes)) bsrc += `\nexport const ${name} = "${code}" as const;\n`;
fs.writeFileSync(BYTECODE_OUT, bsrc);
console.log("Wrote", path.relative(process.cwd(), BYTECODE_OUT));
