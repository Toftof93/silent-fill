// Writes contract ABIs for the web app. Run after `npx hardhat compile`.
const fs = require("fs");
const path = require("path");

const ART = path.join(__dirname, "..", "artifacts", "contracts");
const OUT = path.join(__dirname, "..", "app", "src", "lib", "abi.ts");

const pick = (file, name) => JSON.parse(fs.readFileSync(path.join(ART, file, `${name}.json`), "utf8")).abi;

const abis = {
  auctionAbi: pick("SilentAuction.sol", "SilentAuction"),
  vaultAbi: pick("SilentVault.sol", "SilentVault"),
  oracleAbi: pick("SilentOracle.sol", "SilentOracle"),
  tokenAbi: pick("test/Mocks.sol", "MockERC20"),
};

let src = "// Generated by scripts/export-abi.js. Do not edit.\n";
for (const [name, abi] of Object.entries(abis)) {
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log("Wrote", path.relative(process.cwd(), OUT));
